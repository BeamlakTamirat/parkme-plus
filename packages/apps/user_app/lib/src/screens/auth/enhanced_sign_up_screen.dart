  Future<void> _signUp() async {
    if (!_formKey.currentState!.validate()) return;

    ref.read(isLoadingProvider.notifier).state = true;

    try {
      final authService = ref.read(comprehensiveAuthProvider);
      final result = await authService.signUp(
        email: _emailController.text.trim(),
        password: _passwordController.text,
        fullName: _fullNameController.text.trim(),
        phoneNumber: _phoneController.text.trim().isEmpty
            ? null
            : _phoneController.text.trim(),
        vehiclePlateNumber: _includeVehicleInfo &&
                _vehiclePlateController.text.trim().isNotEmpty
            ? _vehiclePlateController.text.trim()
            : null,
        vehicleModel: _includeVehicleInfo &&
                _vehicleModelController.text.trim().isNotEmpty
            ? _vehicleModelController.text.trim()
            : null,
        vehicleColor: _includeVehicleInfo &&
                _vehicleColorController.text.trim().isNotEmpty
            ? _vehicleColorController.text.trim()
            : null,
      );

      if (mounted) {
        if (result.success) {
          // Refresh user data to ensure we get the latest user info
          ref.invalidate(currentUserProvider);
          ref.invalidate(isAuthenticatedProvider);

          context.showSuccessNotification(
            result.message,
            icon: Icons.person_add,
          );
          context.go('/home');
        } else {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text(result.message),
              backgroundColor: Colors.red,
            ),
          );
        }
      }
    } finally {
      if (mounted) {
        ref.read(isLoadingProvider.notifier).state = false;
      }
    }
  }
